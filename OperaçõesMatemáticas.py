# Entrada de dados
n1 = float(input("Digite o 1° numero: "))
n2 = float(input("Digite o 2° numero: "))
# Saída de dados com as 4 operações
print (f"A soma dos dois numeros é: {n1 + n2}")
print (f"A subtração dos dois numeros é: {n1 - n2}")
print (f"A multiplicação dos dois numeros é: {n1 * n2}")
print (f"A divisão numeros é: {n1 / n2}")